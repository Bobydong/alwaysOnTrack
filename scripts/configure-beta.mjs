import { readFile, writeFile } from 'node:fs/promises'
import { randomBytes } from 'node:crypto'
import { loadEnv } from 'vite'

const value = process.argv[2]
let url
try { url = new URL(value) } catch { throw new Error('Usage: npm run beta:configure -- https://YOUR-BACKEND-HOST') }
if (url.protocol !== 'https:' || url.username || url.password || url.pathname !== '/' || url.search || url.hash) throw new Error('Supply an HTTPS origin without a path, query, or credentials.')
let local = await readFile('.env.local', 'utf8').catch(e => { if (e.code === 'ENOENT') return ''; throw e })
const existing = loadEnv('production', process.cwd(), '').DEMO_ACCESS_TOKEN
const token = /^[a-f0-9]{64}$/.test(existing || '') ? existing : randomBytes(32).toString('hex')
const line = `DEMO_ACCESS_TOKEN=${token}`
local = /^DEMO_ACCESS_TOKEN=.*$/m.test(local) ? local.replace(/^DEMO_ACCESS_TOKEN=.*$/m, line) : `${local.trimEnd()}\n\n# Shared access for the private demo beta; not a provider API key.\n${line}\n`
await writeFile('.env.local', local)
await writeFile('.env.beta.local', `# Generated by beta:configure. Keep this file local.\nCOMPANION_URL=${url.origin}\n`)
console.log('Beta backend configured. Access token saved locally (not printed). Restart the backend, then run npm run beta:pack.')
